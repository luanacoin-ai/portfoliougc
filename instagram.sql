-- ============================================================================
-- TABELA: ig_automations
-- Cada linha é uma automação: "quando alguém comentar tal palavra, mande tal
-- conversa no direct". A conversa INTEIRA mora na coluna "flow" (a Mensagem 1
-- é o primeiro item de flow.steps). Não existem colunas separadas de mensagem
-- ou link: tudo fica no fluxo, pra ter um caminho só.
-- ============================================================================
create table if not exists public.ig_automations (
  id uuid primary key default gen_random_uuid(),
  nome text not null default '',
  keyword text not null default '',                  -- palavras separadas por vírgula
  match_any boolean not null default false,           -- true = qualquer comentário dispara
  active boolean not null default true,
  media_ids text[] not null default '{}',             -- posts escolhidos (vazio = todos os posts)
  public_reply text not null default '',              -- resposta pública no comentário
  public_reply_variants text[] not null default '{}', -- variações A/B da resposta pública
  flow jsonb not null default '{"steps": []}'::jsonb, -- a conversa de botões
  asset_ids text[] not null default '{}',             -- arquivos anexados na Mensagem 1
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);


-- ============================================================================
-- TABELA: ig_leads
-- Cada pessoa que entrou numa automação. A chave é o id da pessoa no Instagram.
-- ============================================================================
create table if not exists public.ig_leads (
  ig_user_id text primary key,
  username text,
  last_source text,                -- comment / dm / story_reply
  last_keyword text,
  automation_id uuid,
  flow_step text,                  -- em que passo da conversa a pessoa está
  link_sent boolean not null default false,
  expecting jsonb,                 -- quando um passo pede um dado (e-mail, telefone)
  tags text[] not null default '{}',
  email text,
  telefone text,
  campos jsonb not null default '{}'::jsonb, -- outros dados capturados
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);


-- ============================================================================
-- TABELA: ig_deliveries
-- O diário de tudo que o sistema tentou enviar: deu certo, deu erro, ficou na
-- fila ou foi pulado. É o primeiro lugar pra olhar quando algo não chegou.
-- ============================================================================
create table if not exists public.ig_deliveries (
  id bigint generated by default as identity primary key,
  ig_user_id text,
  automation_id uuid,
  canal text,                      -- private_reply (resposta ao comentário) / dm
  tipo text,                       -- flow / link / text / asset
  status text not null default 'ok'
    check (status in ('ok', 'erro', 'na_fila', 'pulado')),
  motivo text,
  ts timestamptz not null default now()
);
create index if not exists ig_deliveries_usuario_ts on public.ig_deliveries (ig_user_id, ts desc);
create index if not exists ig_deliveries_ts on public.ig_deliveries (ts desc);


-- ============================================================================
-- TABELA: ig_send_queue
-- Fila de envios que o freio segurou (passou do teto por minuto/hora/dia).
-- O robô "ig-scheduler" esvazia essa fila a cada minuto.
-- ============================================================================
create table if not exists public.ig_send_queue (
  id bigint generated by default as identity primary key,
  comment_id text not null unique,
  automation_id uuid,
  ig_user_id text,
  username text,
  status text not null default 'pendente'
    check (status in ('pendente', 'enviado', 'erro', 'expirado')),
  tentativas integer not null default 0,
  created_at timestamptz not null default now(),
  sent_at timestamptz,
  last_error text
);
create index if not exists ig_send_queue_status on public.ig_send_queue (status, created_at);


-- ============================================================================
-- TABELA: ig_send_budget
-- O CONTADOR do freio. Uma linha só (id = 'private_reply'). As funções
-- take_send_slot e record_send_result (mais abaixo) leem e escrevem aqui.
-- Sem esta tabela o freio não tem onde contar e nenhuma DM por comentário sai.
-- ============================================================================
create table if not exists public.ig_send_budget (
  id text primary key,
  min_count integer not null default 0,
  hour_count integer not null default 0,
  day_count integer not null default 0,
  min_start timestamptz,
  hour_start timestamptz,
  day_start timestamptz,
  err_streak integer not null default 0,    -- falhas seguidas (as "duras" pesam mais)
  cap_minute integer not null default 6,    -- tetos CONSERVADORES, bem abaixo do limite do Instagram
  cap_hour integer not null default 60,
  cap_day integer not null default 180,
  paused_until timestamptz                  -- enquanto estiver no futuro, nada sai (disjuntor)
);

-- A linha inicial, com os tetos padrão.
insert into public.ig_send_budget (id) values ('private_reply') on conflict (id) do nothing;


-- ============================================================================
-- TABELA: ig_scheduled
-- Passos da conversa com atraso ("mande a próxima mensagem daqui a X segundos").
-- ============================================================================
create table if not exists public.ig_scheduled (
  id bigint generated by default as identity primary key,
  ig_user_id text not null,
  automation_id uuid not null,
  step_id text not null,
  send_at timestamptz not null,
  sent boolean not null default false,
  created_at timestamptz not null default now()
);
create index if not exists ig_scheduled_pendentes on public.ig_scheduled (sent, send_at);


-- ============================================================================
-- TABELA: ig_assets
-- A biblioteca de arquivos (PDF, áudio, foto, vídeo) que você anexa nas
-- mensagens. O arquivo em si fica na pasta "ig-arquivos" (criada mais abaixo).
-- ============================================================================
create table if not exists public.ig_assets (
  id uuid primary key default gen_random_uuid(),
  nome text not null,
  tipo text not null default 'file'
    check (tipo in ('image', 'audio', 'video', 'file')),
  public_url text not null,
  storage_path text,               -- caminho do arquivo na pasta ig-arquivos (pra poder apagar)
  attachment_id text,              -- guarda o id do Instagram pra reaproveitar o envio
  size_bytes bigint,
  created_at timestamptz not null default now()
);


-- ============================================================================
-- TABELA: ig_token_status
-- Quando o token do Instagram vence e se a última renovação deu certo.
-- ============================================================================
create table if not exists public.ig_token_status (
  id text primary key,             -- sempre 'main'
  expires_at timestamptz,
  last_ok boolean,
  last_error text,
  last_refreshed_at timestamptz,
  updated_at timestamptz not null default now()
);


-- ============================================================================
-- TABELA: ig_bot_sends
-- Os ids das mensagens que o PRÓPRIO sistema enviou. Quando o Instagram avisa
