create table if not exists public.ig_processed_events (
  id text primary key,
  created_at timestamptz not null default now()
);


-- ============================================================================
-- O FREIO (OBRIGATÓRIO): duas funções que respeitam o teto de envio
-- ============================================================================
-- AVISO: sem estas duas funções o freio "falha fechado": NENHUMA DM por
-- comentário sai (tudo vai pra fila e a fila nunca anda). Não pule este passo.
--
-- take_send_slot: tenta pegar uma "ficha" de envio. Conta por minuto, por hora
-- e por dia na tabela ig_send_budget, com trava (FOR UPDATE) pra duas
-- mensagens ao mesmo tempo não furarem o teto. Devolve true se pode enviar.
-- Se o disjuntor estiver ligado (paused_until no futuro), devolve false.
create or replace function public.take_send_slot(p_key text)
returns boolean
language plpgsql
security definer
set search_path = public
as $$
declare
  b public.ig_send_budget%rowtype;
  agora timestamptz := now();
begin
  insert into public.ig_send_budget (id) values (p_key) on conflict (id) do nothing;
  select * into b from public.ig_send_budget where id = p_key for update;

  if b.paused_until is not null and b.paused_until > agora then
    return false;
  end if;

  -- zera cada janela quando ela vence
  if b.min_start is null or agora - b.min_start >= interval '1 minute' then
    b.min_start := agora;  b.min_count := 0;
  end if;
  if b.hour_start is null or agora - b.hour_start >= interval '1 hour' then
    b.hour_start := agora; b.hour_count := 0;
  end if;
  if b.day_start is null or agora - b.day_start >= interval '1 day' then
    b.day_start := agora;  b.day_count := 0;
  end if;

  -- passou de algum teto: guarda as janelas zeradas e diz "não pode"
  if b.min_count >= b.cap_minute or b.hour_count >= b.cap_hour or b.day_count >= b.cap_day then
    update public.ig_send_budget
       set min_start = b.min_start, min_count = b.min_count,
           hour_start = b.hour_start, hour_count = b.hour_count,
           day_start = b.day_start, day_count = b.day_count
     where id = p_key;
    return false;
  end if;

  -- pode enviar: gasta uma ficha em cada janela
  update public.ig_send_budget
     set min_start = b.min_start, min_count = b.min_count + 1,
         hour_start = b.hour_start, hour_count = b.hour_count + 1,
         day_start = b.day_start, day_count = b.day_count + 1
   where id = p_key;
  return true;
end;
$$;

-- record_send_result: anota se o envio deu certo, pra alimentar o disjuntor.
-- Falha "dura" (bloqueio, limite, token ruim) pesa 3; falha comum pesa 1.
-- Ao chegar em 9 seguidas, o envio pausa por 3 horas. Um envio com sucesso
-- zera a contagem.
create or replace function public.record_send_result(p_key text, p_ok boolean, p_hard boolean)
returns void
language plpgsql
security definer
set search_path = public
as $$
begin
  insert into public.ig_send_budget (id) values (p_key) on conflict (id) do nothing;

  if p_ok then
    update public.ig_send_budget set err_streak = 0 where id = p_key;
  else
    update public.ig_send_budget
       set err_streak = err_streak + (case when p_hard then 3 else 1 end)
     where id = p_key;
    update public.ig_send_budget
       set paused_until = now() + interval '3 hours', err_streak = 0
     where id = p_key and err_streak >= 9;
  end if;
end;
$$;

-- Só os robôs do servidor (service_role) podem chamar o freio. Nem o site
-- público nem quem está logado conseguem mexer nele.
revoke all on function public.take_send_slot(text) from public, anon, authenticated;
revoke all on function public.record_send_result(text, boolean, boolean) from public, anon, authenticated;
grant execute on function public.take_send_slot(text) to service_role;
grant execute on function public.record_send_result(text, boolean, boolean) to service_role;


-- ============================================================================
-- REGRAS DE ACESSO (RLS): só VOCÊ, logada com o seu e-mail, lê e escreve
-- ============================================================================
-- Os contatos (leads) são dados de outras pessoas, então aqui a regra é mais
-- apertada que nas outras abas: não basta estar logada, tem que ser o seu
-- e-mail. Se um dia você trocar o e-mail do painel, troque aqui também.
--
-- As funções na nuvem usam a chave de serviço do Supabase, que ignora o RLS,
-- então elas conseguem escrever mesmo com tudo trancado. O público anônimo
-- não enxerga nada destas tabelas.
create or replace function public.ig_eh_admin()
returns boolean
language sql
stable
as $$
  select coalesce(auth.jwt() ->> 'email', '') = 'luanacoin@gmail.com'
$$;

