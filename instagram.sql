-- ============================================================================
-- PASTA DE ARQUIVOS: ig-arquivos
-- ============================================================================
-- Os arquivos que você anexa nas mensagens (PDF, áudio, foto, vídeo) ficam
-- aqui. A pasta é pública pra leitura porque o Instagram precisa baixar o
-- arquivo por um link pra entregar pra pessoa. Só você consegue enviar e apagar.
-- Limite de 25 MB por arquivo (o teto do Instagram).
insert into storage.buckets (id, name, public, file_size_limit)
values ('ig-arquivos', 'ig-arquivos', true, 26214400)
on conflict (id) do update set public = true, file_size_limit = 26214400;

drop policy if exists "ig_arquivos_enviar_somente_admin" on storage.objects;
create policy "ig_arquivos_enviar_somente_admin"
  on storage.objects for insert to authenticated
  with check ( bucket_id = 'ig-arquivos' and public.ig_eh_admin() );

drop policy if exists "ig_arquivos_apagar_somente_admin" on storage.objects;
create policy "ig_arquivos_apagar_somente_admin"
  on storage.objects for delete to authenticated
  using ( bucket_id = 'ig-arquivos' and public.ig_eh_admin() );


